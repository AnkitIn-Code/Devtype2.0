/**
 * Clean up legacy storage key if present to prevent fake mock unlocks
 */
function cleanLegacyStorage() {
  try {
    if (localStorage.getItem('codetype_achievements_v1')) {
      localStorage.removeItem('codetype_achievements_v1');
    }
  } catch (e) {
    // Ignore in non-browser contexts
  }
}

/**
 * Load achievements from localStorage scoped to a specific user ID,
 * or return pristine clean achievements if freshly registered.
 */
export function getStoredAchievements(userId = null) {
  cleanLegacyStorage();
  const key = userId ? `devtype_achievements_${userId}` : 'devtype_achievements_guest';
  try {
    const raw = localStorage.getItem(key);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.error('Failed to parse stored achievements', e);
  }
  // Return pristine, locked achievements for fresh accounts
  return INITIAL_ACHIEVEMENTS.map((ach) => ({
    ...ach,
    unlocked: false,
    unlockedAt: null,
    progress: 0,
  }));
}

/**
 * Save achievements to localStorage scoped to user ID
 */
export function saveStoredAchievements(achievements, userId = null) {
  cleanLegacyStorage();
  const key = userId ? `devtype_achievements_${userId}` : 'devtype_achievements_guest';
  try {
    localStorage.setItem(key, JSON.stringify(achievements));
  } catch (e) {
    console.error('Failed to persist achievements', e);
  }
}
