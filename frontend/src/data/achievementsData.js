const STORAGE_KEY = 'codetype_achievements_v1';

/**
 * Load achievements from localStorage or fallback to default
 */
export function getStoredAchievements() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      return JSON.parse(raw);
    }
  } catch (e) {
    console.error('Failed to parse stored achievements', e);
  }
  return INITIAL_ACHIEVEMENTS;
}

/**
 * Save achievements to localStorage
 */
export function saveStoredAchievements(achievements) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(achievements));
  } catch (e) {
    console.error('Failed to persist achievements', e);
  }
}
